import { afterEach, expect, it, vi } from 'vitest'
import { queryService } from '../query'

afterEach(() => vi.unstubAllGlobals())
const tick = () => new Promise((r) => setTimeout(r, 20))
function stream(parts: string[]) {
  return new ReadableStream({ start(c) { parts.forEach((p) => c.enqueue(new TextEncoder().encode(p))); c.close() } })
}
it('parses split CRLF frames and settles once while releasing its reader', async () => {
  const body = stream(['data: {"type":"delta","text":"hi"}\r', '\n\r\n', 'data:{"type":"done","content":"hi"}\r\n\r\n', 'data:{"type":"error"}\n\n'])
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, body }))
  const onDone = vi.fn(), onError = vi.fn(), onDelta = vi.fn()
  queryService.executeStream({ query: 'q' }, { onDone, onError, onDelta })
  await tick()
  expect(onDelta).toHaveBeenCalledWith('hi')
  expect(onDone).toHaveBeenCalledTimes(1)
  expect(onError).not.toHaveBeenCalled()
  expect(body.locked).toBe(false)
})
it('delivers measured queue and turn metadata without inventing missing values', async () => {
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, body: stream(['data:{"type":"done","content":"ok","queue_elapsed_ms":10,"turn_elapsed_ms":20}\n\n']) }))
  const onDone = vi.fn()
  queryService.executeStream({ query: 'q' }, { onDone })
  await tick()
  expect(onDone.mock.calls[0][2]).toEqual({ queueElapsedMs: 10, turnElapsedMs: 20 })
})
it('treats premature EOF as a terminal failure', async () => {
  const body = stream(['data: {"type":"delta","text":"partial"}\n\n'])
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, body }))
  const onError = vi.fn()
  queryService.executeStream({ query: 'q' }, { onError })
  await tick()
  expect(onError).toHaveBeenCalledTimes(1)
  expect(body.locked).toBe(false)
})
it('settles abort even when fetch has not resolved', async () => {
  vi.stubGlobal('fetch', vi.fn(() => new Promise(() => {})))
  const onError = vi.fn()
  const ctrl = queryService.executeStream({ query: 'q' }, { onError })
  ctrl.abort(); ctrl.abort()
  await tick()
  expect(onError).toHaveBeenCalledTimes(1)
})
it('exposes a bounded plain HTTP detail', async () => {
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: false, status: 503, json: async () => ({ detail: 'busy' }) }))
  const onError = vi.fn()
  queryService.executeStream({ query: 'q' }, { onError })
  await tick()
  expect(onError).toHaveBeenCalledWith('HTTP 503: busy')
})
it('settles server error once and ignores trailing events', async () => {
  const body = stream(['data:{"type":"error","message":"broken"}\n\ndata:{"type":"done"}\n\n'])
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, body }))
  const onError = vi.fn(), onDone = vi.fn()
  queryService.executeStream({ query: 'q' }, { onError, onDone })
  await tick()
  expect(onError).toHaveBeenCalledOnce(); expect(onDone).not.toHaveBeenCalled()
  expect(body.locked).toBe(false)
})
it('settles a rejected network connection once', async () => {
  vi.stubGlobal('fetch', vi.fn().mockRejectedValue(new Error('offline')))
  const onError = vi.fn()
  queryService.executeStream({ query: 'q' }, { onError })
  await tick()
  expect(onError).toHaveBeenCalledTimes(1)
  expect(onError).toHaveBeenCalledWith('offline')
})
it('extracts a simple structured HTTP message', async () => {
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: false, status: 422, json: async () => ({ detail: { message: 'invalid query' } }) }))
  const onError = vi.fn()
  queryService.executeStream({ query: 'q' }, { onError })
  await tick()
  expect(onError).toHaveBeenCalledWith('HTTP 422: invalid query')
})
it('does not process buffered done after a delta callback aborts reception', async () => {
  const body = stream(['data:{"type":"delta","text":"partial"}\n\ndata:{"type":"done","content":"answer"}\n\n'])
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, body }))
  const onError = vi.fn(), onDone = vi.fn()
  const ctrl = queryService.executeStream({ query: 'q' }, { onError, onDone, onDelta: () => ctrl.abort() })
  await tick()
  expect(onError).toHaveBeenCalledOnce()
  expect(onDone).not.toHaveBeenCalled()
  expect(body.locked).toBe(false)
})
